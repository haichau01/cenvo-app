namespace Cenvo.Modules.Inventory.Domain;

public enum StockDocumentType
{
    /// <summary>Purchase receipt from a supplier.</summary>
    PurchaseReceipt = 1,
    /// <summary>Write-off (damaged, expired).</summary>
    DisposalIssue = 2,
    /// <summary>Internal use.</summary>
    InternalIssue = 3,
    /// <summary>Transfer: issued from the source warehouse → destination confirms receipt (may be another branch).</summary>
    Transfer = 4,
    /// <summary>Stocktake — adjusts differences automatically.</summary>
    Stocktake = 5,
    /// <summary>Sale issue (generated automatically by POS / sales).</summary>
    SaleIssue = 6,
    /// <summary>Opening balance.</summary>
    OpeningBalance = 7,
}

public enum TransferState { None = 0, InTransit = 1, Received = 2 }

public static class StockDocumentTypes
{
    /// <summary>Document types users may create manually (SaleIssue is generated by sales only).</summary>
    public static readonly StockDocumentType[] Manual =
    [
        StockDocumentType.PurchaseReceipt, StockDocumentType.DisposalIssue, StockDocumentType.InternalIssue,
        StockDocumentType.Transfer, StockDocumentType.Stocktake, StockDocumentType.OpeningBalance,
    ];

    public static string CodePrefix(this StockDocumentType type) => type switch
    {
        StockDocumentType.PurchaseReceipt => "PN",
        StockDocumentType.DisposalIssue => "XH",
        StockDocumentType.InternalIssue => "XN",
        StockDocumentType.Transfer => "CK",
        StockDocumentType.Stocktake => "KK",
        StockDocumentType.SaleIssue => "XB",
        StockDocumentType.OpeningBalance => "TD",
        _ => throw new ArgumentOutOfRangeException(nameof(type)),
    };
}
